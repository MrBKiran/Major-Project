/**
 * Generates tokens.css — Tailwind v4 theme variables — from src/index.js.
 *   npm run tokens          (from the repo root)
 * A test fails if tokens.css differs from what this renders, so a hand edit
 * cannot drift from the source.
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { chart, color, day, font, night, radius, text } from "../src/index.js";

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

/** Semantic CSS name for a mode token. */
function semantic(key) {
  if (["page", "panel", "card", "inset", "insetStrong"].includes(key)) return `--color-surface-${kebab(key)}`;
  return `--color-${kebab(key)}`;
}

// Names the pages use today. ink-* is the surface ramp; slate-* was repointed
// at a light ground with its direction kept (higher number = more prominent).
// Phase 2 moves every page onto the semantic names and deletes these.
const LEGACY = {
  "ink-900": "page", "ink-800": "card", "ink-700": "inset", "ink-600": "insetStrong", edge: "border",
  "slate-100": "fgStrong", "slate-200": "fg", "slate-300": "fgSecondary", "slate-400": "fgTertiary",
  "slate-500": "fgMuted", "slate-600": "fgSubtle", "slate-700": "fgDecorative",
};

export function renderCss() {
  const lines = [
    "/* Generated by packages/tokens/scripts/build-css.js from src/index.js — do not edit. */",
    "",
    "@theme {",
    "  /* Legacy names the pages use today (Phase 2 migrates them to the semantic names). */",
    ...Object.entries(LEGACY).map(([name, key]) => `  --color-${name}: ${day[key]};`),
    "",
    "  /* Semantic, day values (night overrides below). */",
    ...Object.entries(day).map(([key, value]) => `  ${semantic(key)}: ${value};`),
    "",
    "  /* Brand and severity. */",
    ...Object.entries(color).map(([key, value]) => `  --color-${kebab(key)}: ${value};`),
    "",
    "  /* Chart series: bg-chart-baseline etc., for legends drawn outside the chart. */",
    ...Object.entries(chart).map(([key, value]) => `  --color-chart-${kebab(key)}: ${value};`),
    "",
    `  --font-sans: ${font.sans.replace(/'/g, '"')};`,
    `  --font-mono: ${font.mono.replace(/'/g, '"')};`,
    "",
    "  /* Type scale: text-caption … text-display-lg. */",
    ...Object.entries(text).flatMap(([key, t]) => [
      `  --text-${kebab(key)}: ${t.size}px;`,
      `  --text-${kebab(key)}--line-height: ${t.lineHeight};`,
    ]),
    "",
    "  /* Radius scale: rounded-chip … rounded-pill. */",
    ...Object.entries(radius).map(([key, r]) => `  --radius-${kebab(key)}: ${r}px;`),
    "}",
    "",
    ":root[data-theme=\"night\"] {",
    ...Object.entries(night).map(([key, value]) => `  ${semantic(key)}: ${value};`),
    "}",
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL("../tokens.css", import.meta.url), renderCss());
  console.log("wrote packages/tokens/tokens.css");
}
